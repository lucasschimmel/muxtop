//! Bounded file sink shared by the client and daemon tracing workers.

use std::fs::{File, OpenOptions};
use std::io::{self, Seek, SeekFrom, Write};
use std::path::Path;

/// Maximum on-disk size of each application's log file.
pub const MAX_LOG_BYTES: u64 = 2 * 1024 * 1024;
/// Bounded queue: overload drops diagnostic records instead of blocking collection.
pub const LOG_QUEUE_LINES_LIMIT: usize = 256;

/// A single bounded log segment. Once full, a new segment replaces its contents.
/// Feed this sink through a non-blocking tracing worker so disk I/O stays off
/// collection and admission paths.
pub struct BoundedLog {
    file: File,
    size: u64,
    limit: u64,
}

impl BoundedLog {
    pub fn open(path: &Path) -> io::Result<Self> {
        Self::with_limit(path, MAX_LOG_BYTES)
    }

    fn with_limit(path: &Path, limit: u64) -> io::Result<Self> {
        let file = OpenOptions::new()
            .create(true)
            .write(true)
            .truncate(false)
            .open(path)?;
        let size = file.metadata()?.len();
        let mut sink = Self { file, size, limit };
        if sink.size > limit {
            sink.reset()?;
        } else {
            sink.file.seek(SeekFrom::End(0))?;
        }
        Ok(sink)
    }

    fn reset(&mut self) -> io::Result<()> {
        self.file.set_len(0)?;
        self.file.seek(SeekFrom::Start(0))?;
        self.size = 0;
        Ok(())
    }
}

impl Write for BoundedLog {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        let keep = bytes.len().min(self.limit as usize);
        if self.size.saturating_add(keep as u64) > self.limit {
            self.reset()?;
        }
        self.file.write_all(&bytes[bytes.len() - keep..])?;
        self.size += keep as u64;
        Ok(bytes.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        self.file.flush()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // @generated by:gauntlet run:muxtop-audit-fixes
    #[test]
    fn t_ac_05_log_file_stays_bounded_across_reopen_and_large_records() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("bounded.log");
        std::fs::write(&path, [b'x'; 100]).unwrap();
        let mut sink = BoundedLog::with_limit(&path, 16).unwrap();
        for record in [b"first".as_slice(), b"second-record", &[b'z'; 40]] {
            sink.write_all(record).unwrap();
            sink.flush().unwrap();
            assert!(std::fs::metadata(&path).unwrap().len() <= 16);
        }
        drop(sink);
        let mut sink = BoundedLog::with_limit(&path, 16).unwrap();
        sink.write_all(b"new").unwrap();
        assert_eq!(std::fs::read(path).unwrap(), b"new");
    }
}
